"""The committed breakout board must pass its placement check.

`hardware/breakout/breakout.kicad_pcb` is generated by `hardware/gen/gen_breakout_pcb.py`
and then routed by a person, in pcbnew. What must stay true through both is what
`hardware/gen/check_breakout_placement.py` asserts: every netlist reference placed once, on
its contract net; each panel connector at its panel position; no part on the wrong side of
a barrier; no copper in a slot. A part on the wrong side of a barrier leaves the netlist,
ERC and DRC all clean, so nothing else in this repository would say a word.

The check reads the committed board file and the committed netlist contract, so this runs
unconditionally in CI with no KiCad installed. The three mutations below are negative
controls: each breaks the board file in one way the check exists to catch, and asserts
that it does.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).parents[2]
sys.path.insert(0, str(REPO / "hardware" / "gen"))
import check_breakout_placement as chk  # noqa: E402

HW = REPO / "hardware" / "breakout"


@pytest.fixture(scope="module")
def board_text() -> str:
    return (HW / "breakout.kicad_pcb").read_text()


@pytest.fixture(scope="module")
def contract() -> dict:
    return json.loads((HW / "netlist-contract.json").read_text())


def _move(text: str, ref: str, x: float, y: float) -> str:
    """The board text with one footprint's own `(at ...)` rewritten."""
    prop = text.index(f'(property "Reference" "{ref}"')
    start = text.rindex("(footprint ", 0, prop)
    head = text[start:prop]
    moved, n = re.subn(r"\(at [^)]*\)", f"(at {x} {y})", head, count=1)
    assert n == 1
    return text[:start] + moved + text[prop:]


def test_committed_board_passes_the_placement_check(board_text, contract):
    fails, report = chk.run_checks(
        board_text, contract,
        (HW / "breakout.kicad_pro").read_text(), (HW / "breakout.kicad_dru").read_text(),
    )
    assert fails == [], "\n".join(fails[:40])
    assert report["placed"] == report["netlist_refs"] + len(chk.MECHANICAL)
    assert report["pads_on_wrong_side"] == 0
    assert report["pads_in_slots"] == 0
    assert report["panel_connectors"] == len(chk.PANEL)


def test_a_part_moved_across_a_barrier_fails(board_text, contract):
    # R123 is an NI-side pull-up (NI_5V). Put it in the DGND region.
    fails, _ = chk.run_checks(_move(board_text, "R123", 120.0, 120.0), contract)
    assert any(f.startswith("4:") and "R123" in f for f in fails), fails[:5]


def test_a_part_dropped_into_a_slot_fails(board_text, contract):
    # C6 is a DGND bypass capacitor. Put it on the NI line, over the slot.
    fails, _ = chk.run_checks(_move(board_text, "C6", chk.NI_X, 130.0), contract)
    assert any(f.startswith("5:") and "C6" in f and "slot" in f for f in fails), fails[:5]


def test_a_panel_connector_off_its_position_fails(board_text, contract):
    f = next(fp for fp in chk.read_board(board_text)["footprints"] if fp.ref == "J20")
    fails, _ = chk.run_checks(_move(board_text, "J20", f.x + 0.5, f.y), contract)
    assert any(x.startswith("3:") and "J20" in x for x in fails), fails[:5]


def test_a_missing_reference_fails(board_text, contract):
    renamed = board_text.replace('(property "Reference" "R5"', '(property "Reference" "R9999"', 1)
    fails, _ = chk.run_checks(renamed, contract)
    assert any("R5 is in the netlist and not on the board" in f for f in fails)
    assert any("R9999 is on the board and not in the netlist" in f for f in fails)


def test_every_declared_exception_cites_a_constraint():
    for ref, (region, why) in chk.DECLARED_HOME.items():
        assert region in chk.REGIONS and re.search(r"[A-Z]-\d+", why), ref
    for net, why in chk.EXPECTED_CROSSINGS.items():
        assert re.search(r"[A-Z]-\d+", why), net
